#!/usr/bin/env sh
# Creates deploy/.env with fresh random secrets the first time, so `make up` works on a clean clone
# and no password is ever committed. An existing file keeps its values; a variable added in a later
# version is appended with a fresh value.
set -eu

file="${1:-deploy/.env}"

hex() { od -An -N24 -tx1 /dev/urandom | tr -d ' \n'; }
key32() { head -c 32 /dev/urandom | base64 | tr -d '\n'; }

# Every variable deploy/compose.yaml requires, with how to generate it.
values() {
  cat <<EOF
POSTGRES_PASSWORD=$(hex)
CLICKHOUSE_PASSWORD=$(hex)
REDIS_PASSWORD=$(hex)
S3_ACCESS_KEY=voicegateway
S3_SECRET_KEY=$(hex)
VOICEGATEWAY_SECRET_KEY=$(key32)
EOF
}

umask 077
if [ ! -f "$file" ]; then
  # Write to a temporary file and rename it into place, so an interrupted run never leaves a
  # partial deploy/.env that later runs would keep.
  tmp="$(mktemp "${file}.XXXXXX")"
  trap 'rm -f "$tmp"' EXIT
  {
    echo "# Local secrets for deploy/compose.yaml. Generated by tools/scripts/dev-env.sh; never commit this file."
    values
  } >"$tmp"
  mv "$tmp" "$file"
  trap - EXIT
  echo "created $file with random secrets"
  exit 0
fi

values | while IFS= read -r line; do
  name="${line%%=*}"
  if ! grep -q "^${name}=" "$file"; then
    printf '%s\n' "$line" >>"$file"
    echo "added $name to $file"
  fi
done
